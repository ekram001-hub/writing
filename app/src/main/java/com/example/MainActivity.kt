class MainActivity : ComponentActivity() {
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        try {
            enableEdgeToEdge()
        } catch (e: Throwable) {
            // Ignore edge-to-edge failure on older/custom OEM Android ROMs
        }

        val settingsRepo = SettingsRepository.getInstance(applicationContext)

        setContent {
            var startupError by remember { mutableStateOf<String?>(null) }

            if (startupError != null) {
                Surface(
                    modifier = Modifier.fillMaxSize(),
                    color = MaterialTheme.colorScheme.background
                ) {
                    Box(
                        modifier = Modifier
                            .fillMaxSize()
                            .padding(24.dp),
                        contentAlignment = Alignment.Center
                    ) {
                        Card(
                            modifier = Modifier.fillMaxWidth(),
                            colors = CardDefaults.cardColors(
                                containerColor = MaterialTheme.colorScheme.surface
                            ),
                            shape = RoundedCornerShape(16.dp),
                            border = CardDefaults.outlinedCardBorder()
                        ) {
                            Column(
                                modifier = Modifier.padding(20.dp),
                                horizontalAlignment = Alignment.CenterHorizontally,
                                verticalArrangement = Arrangement.Center
                            ) {
                                Icon(
                                    imageVector = Icons.Filled.Warning,
                                    contentDescription = null,
                                    tint = MaterialTheme.colorScheme.error,
                                    modifier = Modifier.size(48.dp)
                                )
                                Spacer(modifier = Modifier.height(12.dp))
                                Text(
                                    text = "Initialization Error",
                                    style = MaterialTheme.typography.titleLarge.copy(fontWeight = FontWeight.Bold),
                                    color = MaterialTheme.colorScheme.onSurface
                                )
                                Spacer(modifier = Modifier.height(8.dp))
                                Text(
                                    text = startupError ?: "An unexpected error occurred.",
                                    style = MaterialTheme.typography.bodySmall,
                                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                                    textAlign = TextAlign.Center
                                )
                                Spacer(modifier = Modifier.height(16.dp))
                                val context = LocalContext.current
                                Button(
                                    onClick = {
                                        try {
                                            context.deleteDatabase("microwrite_database.db")
                                        } catch (_: Exception) {}
                                        startupError = null
                                    }
                                ) {
                                    Text("Reset & Start App")
                                }
                            }
                        }
                    }
                }
            } else {
                val settings by settingsRepo.settingsFlow.collectAsStateWithLifecycle(
                    initialValue = AppSettings()
                )

                MicroWriteTheme(themeMode = settings.themeMode) {
                    MicroWriteNavApp()
                }
            }
        }
    }
}
